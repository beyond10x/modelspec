//! The word lists of the site's `modelspec` code highlighter, from the compiler.
//!
//! The reserved words are `syntax::lexer::KEYWORDS`; the built-in functions are the source
//! operators of `resolve::OPERATORS` and the initializer names of the Tensor IR. A few words are
//! recognised by the parser by their text, not by a token; they are listed here and checked against
//! the grammar in the parser's doc comment. `website/src/theme/prism-include-languages.ts` turns the
//! lists into a Prism grammar.

use modelspec_core::ir::tensor::{DType, Initializer};
use modelspec_core::resolve::OPERATORS;
use modelspec_core::syntax::lexer::KEYWORDS;
use serde_json::json;

use crate::Result;

/// The generated file, under `website/data/`.
pub const FILE: &str = "modelspec.grammar.json";

/// Words the parser matches by their text: the optimizer and the devices of a train block.
const PARSER_WORDS: &[&str] = &["sgd", "cpu", "vulkan"];

/// The type constructor the parser matches by its text.
const TENSOR: &str = "Tensor";

/// The grammar's word lists, as JSON.
pub fn document() -> Result<String> {
    let initializers = Initializer::ALL.map(|init| init.to_string());
    let mut builtins: Vec<String> = OPERATORS.iter().map(|(name, _)| name.to_string()).collect();
    builtins.extend(initializers);
    builtins.extend(PARSER_WORDS.iter().map(|word| word.to_string()));
    let document = json!({
        "format": "modelspec-grammar/1",
        "source": "generated by modelspec-docs from the lexer, the operator registry and the parser",
        "keywords": KEYWORDS,
        "builtins": builtins,
        "types": [TENSOR, DType::F32.to_string(), DType::I32.to_string()],
    });
    let text = serde_json::to_string_pretty(&document).map_err(|e| e.to_string())?;
    Ok(text + "\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_parser_word_is_in_the_parser_grammar() {
        let grammar = include_str!("../../modelspec-core/src/syntax/parser.rs");
        for word in PARSER_WORDS.iter().chain([&TENSOR]) {
            assert!(grammar.contains(&format!("\"{word}\"")), "{word}");
        }
    }

    #[test]
    fn the_lists_hold_the_words_of_the_linear_regression_example() {
        let text = document().unwrap();
        let document: serde_json::Value = serde_json::from_str(&text).unwrap();
        let words = |key: &str| -> Vec<String> {
            document[key]
                .as_array()
                .unwrap()
                .iter()
                .map(|w| w.as_str().unwrap().to_owned())
                .collect()
        };
        for word in ["model", "train", "return"] {
            assert!(words("keywords").contains(&word.to_owned()), "{word}");
        }
        for word in ["matmul", "mse", "xavier_uniform", "sgd", "cpu"] {
            assert!(words("builtins").contains(&word.to_owned()), "{word}");
        }
        assert_eq!(words("types"), ["Tensor", "f32", "i32"]);
    }
}
