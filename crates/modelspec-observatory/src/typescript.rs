//! The TypeScript types of the observatory UI, `ui/src/generated/observatory.ts`, generated from
//! the serde types of the stream by `ts-rs` (story:observatory-ui-live-loss-chart), so the UI
//! reads the JSON of a frame with the types the server writes it with. `modelspec-ui-types`
//! writes the file (`task ui-types`) and `--check` compares it (`task ui-types-check`).
//!
//! The file declares [`RunEvent`] and every type it contains, sorted by name. An integer is a
//! TypeScript `number`, as `JSON.parse` reads it; a float is `number | null`, `null` for NaN and
//! ±inf as the JSON writes them.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};

use ts_rs::{Config, TS, TypeVisitor};

use crate::event::RunEvent;

/// The generated file, relative to the repository root.
pub const UI_TYPES_PATH: &str = "ui/src/generated/observatory.ts";

const HEADER: &str = "\
// Generated by `modelspec-ui-types` (`task ui-types`) from the Rust types of
// crates/modelspec-observatory/src/event.rs. Do not edit by hand.
";

/// The content of [`UI_TYPES_PATH`] the Rust types generate now.
pub fn typescript() -> String {
    let config = Config::new().with_large_int("number");
    let mut declarations = Declarations {
        config: &config,
        seen: HashSet::new(),
        by_name: BTreeMap::new(),
    };
    declarations.visit::<RunEvent>();
    let mut out = String::from(HEADER);
    for declaration in declarations.by_name.values() {
        out.push('\n');
        // ts-rs leaves a space at the end of some lines.
        for line in declaration.lines() {
            out.push_str(line.trim_end());
            out.push('\n');
        }
    }
    out
}

/// Visits a type and everything it contains once each, and keeps the declaration of each one
/// that has one, by its TypeScript name.
struct Declarations<'a> {
    config: &'a Config,
    seen: HashSet<TypeId>,
    by_name: BTreeMap<String, String>,
}

impl TypeVisitor for Declarations<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            let mut declaration = T::docs().unwrap_or_default();
            declaration.push_str("export ");
            declaration.push_str(&T::decl(self.config));
            self.by_name.insert(T::ident(self.config), declaration);
        }
        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}
